# ── The live checker ────────────────────────────────────────────────────────

def baseline_book_problems() -> list[str]:
    """The filing against the real estate, judged live."""
    problems: list[str] = []

    # Shape: counts, snapshot, rules.
    if BASELINE_BOOK_FORMAT != "thoughtforge-baseline-book/1":
        problems.append(
            f"BASELINE_BOOK_FORMAT drifted: "
            f"{BASELINE_BOOK_FORMAT}")
    if REGENERATION_COMMAND != \
            "python3 -m benchmarks.baseline_book":
        problems.append(
            f"the regeneration command drifted: "
            f"{REGENERATION_COMMAND}")
    rule_ids = [r["id"] for r in BASELINE_BOOK_RULES]
    if len(rule_ids) != len(set(rule_ids)):
        problems.append("duplicate BASELINE_BOOK_RULES ids")
    for needed in (
            "the_book_is_generated_never_hand_kept",
            "every_pinned_baseline_is_filed_with_its_method",
            "regeneration_is_one_command",
            "drift_fails_the_checker",
            "no_number_is_copied_by_hand",
            "gate_status_comes_from_tf129s_registries",
            "probes_prove_the_checker_can_fail",
            "pass_needs_the_full_book_current",
            "no_new_benchmark_input_was_added",
            "the_baseline_book_baseline_is_not_gated_by_tf129"):
        if needed not in rule_ids:
            problems.append(f"BASELINE_BOOK_RULES lost {needed}")

    # The filed snapshot vs the live recomputation,
    # and every entry judged against its own parts
    # and the registries it binds.
    live_entries = book_entries()
    if [dict(e) for e in live_entries] != [
            dict(e) for e in BOOK_ENTRIES]:
        problems.append(
            "BOOK_ENTRIES drifted from the live "
            "recomputation over the registries")
    if [e["baseline"] for e in live_entries] != [
            b["id"] for b in _harness.BASELINES]:
        problems.append(
            "the book's baselines drifted from the "
            "harness's pinned baselines")
    for entry in live_entries:
        problems.extend(entry_problems(entry))
        baseline = [b for b in _harness.BASELINES
                    if b["id"] == entry["baseline"]][0]
        if {m["metric"]: m["value"]
                for m in entry["metrics"]} != dict(
                    baseline["metrics"]):
            problems.append(
                f"{entry['baseline']}: the book's pinned "
                f"values drifted from the harness pin")

    # Determinism: two renders over the live
    # registries are byte-identical.
    if render_baseline_book_markdown(live_entries) != \
            render_baseline_book_markdown(book_entries()):
        problems.append(
            "the book is not deterministic: two renders "
            "over the live registries differ")

    # The filed doc: present, and exactly the
    # regenerated book (the pure drift checker
    # names any stale section by baseline).
    doc = _REPO_ROOT / BASELINE_BOOK_DOC
    if not doc.exists():
        problems.append(
            f"the baseline book {BASELINE_BOOK_DOC} is "
            f"missing (regenerate with "
            f"{REGENERATION_COMMAND})")
    else:
        problems.extend(book_problems_for(
            doc.read_text(encoding="utf-8"), live_entries))

    # A fresh full run files PASS; partial + empty
    # selections REVIEW.
    result = run_baseline_book()
    if result.verdict != "PASS" or not result.passes:
        problems.append(
            f"the live book run does not file PASS on "
            f"this tree: {result.verdict} "
            f"({result.total_baselines} baselines, doc "
            f"current: {result.doc_current})")
    empty = run_baseline_book(baseline_ids=())
    if empty.total_baselines != 0 or empty.verdict != "REVIEW" \
            or empty.passes:
        problems.append("an empty selection does not file 0 / REVIEW")
    subset = run_baseline_book(
        baseline_ids=("persona_consistency_synthetic_v1",))
    if subset.total_baselines != 1 or subset.verdict != "REVIEW":
        problems.append(
            "a single-baseline selection does not file "
            "its baseline / REVIEW mechanically")

    # The probes all behave.
    probes = run_book_probes()
    if len(probes) != len(BOOK_PROBES) \
            or not all(p["passed"] for p in probes):
        problems.append(
            f"the book probes do not all pass: "
            f"{[p['id'] for p in probes if not p['passed']]}")

    # Harness consistency as filed + every pinned
    # baseline preserved exactly (this slice's
    # included), and the gate's gated set untouched.
    from benchmarks.harness import (
        BASELINES,
        BENCHMARKS,
        baseline_problems,
    )
    from benchmarks.regression_gate import GATED_BASELINE_IDS

    if "baseline_book" not in [b["id"] for b in BENCHMARKS]:
        problems.append("BENCHMARKS lost the baseline_book entry")
    if BASELINE_BOOK_BASELINE_ID not in [b["id"] for b in BASELINES]:
        problems.append("BASELINES lost the baseline-book baseline")
    if BASELINE_BOOK_BASELINE_ID in GATED_BASELINE_IDS:
        problems.append(
            "the baseline-book baseline entered TF-129's "
            "gated set (it is judged by this checker, "
            "not gated)")
    if len(GATED_BASELINE_IDS) != 9:
        problems.append("TF-129's gated set changed shape")
    earlier = baseline_problems()
    if earlier:
        problems.append(
            f"harness baselines moved under the "
            f"baseline book: {earlier}")
    return problems


def baseline_book_as_data() -> dict[str, Any]:
    """The whole filing as plain data, for consumers."""
    result = run_baseline_book()
    probes = run_book_probes()
    return {
        "format": BASELINE_BOOK_FORMAT,
        "doc": BASELINE_BOOK_DOC,
        "regeneration_command": REGENERATION_COMMAND,
        "entries": [dict(e) for e in result.entries],
        "measured": {
            "total_baselines": result.total_baselines,
            "total_pinned_metrics":
                result.total_pinned_metrics,
            "gated_baselines": result.gated_baselines,
            "ungated_baselines": result.ungated_baselines,
            "probes_passed": sum(
                1 for p in probes if p["passed"]),
            "probes_total": len(probes),
            "verdict": result.verdict,
        },
        "probes": probes,
        "rules": [dict(r) for r in BASELINE_BOOK_RULES],
    }


