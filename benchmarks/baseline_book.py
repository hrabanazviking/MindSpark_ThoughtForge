# ── The book entries (built from the live registries) ───────────────────────

def book_entries() -> tuple[dict[str, Any], ...]:
    """The book's entries, built live from the
    registries: one per pinned baseline in the
    harness, in harness filing order, every field
    bound to the registry it files — the pin from
    BASELINES, each metric's method from
    METRIC_DEFINITIONS, the benchmark's kind /
    doc / slice from BENCHMARKS, the measurer
    from the harness's own measurer table, and
    the gate status + per-metric gate tolerances
    from TF-129's registries."""
    benchmarks = {b["id"]: b for b in _harness.BENCHMARKS}
    definitions = {
        (m["benchmark"], m["id"]): m
        for m in _harness.METRIC_DEFINITIONS}
    entries: list[dict[str, Any]] = []
    for baseline in _harness.BASELINES:
        benchmark = benchmarks[baseline["benchmark"]]
        gated = baseline["id"] in _gate.GATED_BASELINE_IDS
        metrics: list[dict[str, Any]] = []
        for metric, value in baseline["metrics"].items():
            definition = definitions[
                (baseline["benchmark"], metric)]
            gate_tolerance = None
            if gated:
                row = _gate.TOLERANCES[baseline["id"]][metric]
                gate_tolerance = {
                    "tolerance": row["tolerance"],
                    "exact": row["exact"]}
            target = baseline["targets"].get(metric)
            metrics.append({
                "metric": metric,
                "value": value,
                "computes": definition["computes"],
                "legacy_name": definition["legacy_name"],
                "target": dict(target) if target else None,
                "gate_tolerance": gate_tolerance,
            })
        measurer = _harness._MEASURERS.get(baseline["id"])
        entries.append({
            "baseline": baseline["id"],
            "benchmark": baseline["benchmark"],
            "benchmark_kind": benchmark["kind"],
            "benchmark_doc": benchmark["doc"],
            "suite_slice": benchmark["suite_slice"],
            "fixture": baseline["fixture"],
            "tolerance": baseline["tolerance"],
            "measured_on": baseline["measured_on"],
            "measurer": measurer.__name__ if measurer else None,
            "gated": gated,
            "gate_status": (
                "gated by TF-129's regression gate"
                if gated else
                "ungated — judged by its own module's checker"),
            "metrics": metrics,
            "excluded_metrics": [
                {"metric": metric, "reason": reason}
                for metric, reason
                in baseline["excluded_metrics"].items()],
            "notes": baseline["notes"],
        })
    return tuple(entries)


#: The filed snapshot: the entries as this module
#: was imported. The checker recomputes them live
#: and names any drift — a registry that moves
#: under a running checker is a finding, exactly
#: as a stale filed book is.
BOOK_ENTRIES: tuple[dict[str, Any], ...] = book_entries()

TOTAL_BASELINES = len(BOOK_ENTRIES)
TOTAL_PINNED_METRICS = sum(
    len(e["metrics"]) for e in BOOK_ENTRIES)


def entry_problems(entry: dict[str, Any]) -> list[str]:
    """Judge ONE book entry against its own parts,
    purely: it must file a baseline, a method, a
    measurer, at least one metric with a method
    line, and a gate status that agrees with its
    metrics' gate tolerances. Pure over the
    entry dict."""
    problems: list[str] = []
    label = entry.get("baseline", "<unnamed>")
    if not entry.get("measured_on"):
        problems.append(
            f"{label}: the entry files no method "
            f"(measured_on) — a baseline without its "
            f"method is not a book entry")
    if not entry.get("measurer"):
        problems.append(
            f"{label}: the entry names no live "
            f"measurer — its pin cannot be re-measured")
    if not entry.get("metrics"):
        problems.append(
            f"{label}: the entry files no metrics")
    for metric in entry.get("metrics", []):
        if not metric.get("computes"):
            problems.append(
                f"{label}: metric {metric.get('metric')} "
                f"files no method (what it computes)")
        if entry.get("gated") and \
                metric.get("gate_tolerance") is None:
            problems.append(
                f"{label}: gated metric "
                f"{metric.get('metric')} files no gate "
                f"tolerance from TF-129's registries")
        if not entry.get("gated") and \
                metric.get("gate_tolerance") is not None:
            problems.append(
                f"{label}: ungated metric "
                f"{metric.get('metric')} files a gate "
                f"tolerance it does not carry")
    return problems


# ── The render (the book itself, deterministic) ─────────────────────────────

def _esc(text: Any) -> str:
    """One markdown cell / line, escaped: pipes
    filed as data in method lines and notes must
    not break the book's tables."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def _value_text(value: Any) -> str:
    return repr(value)


def render_baseline_book_markdown(
    entries: Any = None,
) -> str:
    """Render the book from its entries,
    deterministically — the exact text
    ``python3 -m benchmarks.baseline_book`` files
    as docs/architecture/BASELINE_BOOK.md. Every
    number and method line comes from the
    entries, which come from the live registries;
    nothing is hand-written here but the frame."""
    entries = BOOK_ENTRIES if entries is None else tuple(entries)
    total_metrics = sum(len(e["metrics"]) for e in entries)
    gated = sum(1 for e in entries if e["gated"])
    lines: list[str] = []
    lines.append("# The Baseline Book — TF-134")
    lines.append("")
    lines.append(
        "GENERATED by command from the live registries "
        "(`benchmarks/harness.py` BASELINES / "
        "METRIC_DEFINITIONS / BENCHMARKS and "
        "`benchmarks/regression_gate.py` gate "
        "registries) — do not hand-edit: regenerate "
        f"with `{REGENERATION_COMMAND}`. The checker "
        "(`baseline_book_problems()` in "
        "`benchmarks/baseline_book.py`) recomputes "
        "this book from the registries and fails on "
        "any drift.")
    lines.append("")
    lines.append(f"Format: `{BASELINE_BOOK_FORMAT}`")
    lines.append(
        f"Regeneration command: `{REGENERATION_COMMAND}`")
    lines.append(f"Baselines filed: {len(entries)}")
    lines.append(f"Pinned metrics filed: {total_metrics}")
    lines.append(
        f"Gated baselines (TF-129's regression gate): {gated}")
    lines.append(
        f"Ungated baselines (judged by their own "
        f"checkers): {len(entries) - gated}")
    lines.append("")
    lines.append(
        "Each baseline files its pin beside its method: "
        "the fixture it was measured over, the filed "
        "tolerance, the measured-on line, the harness "
        "measurer that re-measures it live, its gate "
        "status, every pinned metric with its value, "
        "what that metric computes (its method), its "
        "target where one is filed, and its gate "
        "tolerance where it is gated — plus the "
        "metrics deliberately excluded, with their "
        "reasons, and the baseline's own notes.")
    lines.append("")
    for entry in entries:
        lines.append(f"## Baseline `{entry['baseline']}`")
        lines.append("")
        lines.append(
            f"- Benchmark: `{entry['benchmark']}` "
            f"(kind: {entry['benchmark_kind']}; doc: "
            f"`{entry['benchmark_doc']}`)")
        lines.append(f"- Suite slice: {_esc(entry['suite_slice'])}")
        lines.append(f"- Fixture: `{entry['fixture']}`")
        lines.append(
            f"- Tolerance: `{_value_text(entry['tolerance'])}`")
        lines.append(
            f"- Method (measured on): "
            f"{_esc(entry['measured_on'])}")
        lines.append(
            f"- Re-measured live by: "
            f"`{entry['measurer']}()` in "
            f"`benchmarks/harness.py`")
        lines.append(f"- Gate status: {entry['gate_status']}")
        lines.append("")
        lines.append(
            "| Metric | Pinned value | What it computes "
            "(method) | Target | Gate tolerance |")
        lines.append("|---|---|---|---|---|")
        for metric in entry["metrics"]:
            computes = _esc(metric["computes"])
            if metric["legacy_name"]:
                computes += (
                    f" (filed under the legacy name "
                    f"`{metric['legacy_name']}`)")
            if metric["target"] is None:
                target_text = "—"
            else:
                target_text = (
                    f"{_value_text(metric['target']['target'])} "
                    f"(met: {metric['target']['met']})")
            if metric["gate_tolerance"] is None:
                gate_text = "not gated"
            elif metric["gate_tolerance"]["exact"]:
                gate_text = "exact"
            else:
                gate_text = _value_text(
                    metric["gate_tolerance"]["tolerance"])
            lines.append(
                f"| `{metric['metric']}` | "
                f"{_value_text(metric['value'])} | "
                f"{computes} | {target_text} | {gate_text} |")
        lines.append("")
        if entry["excluded_metrics"]:
            lines.append("Excluded metrics (never pinned):")
            lines.append("")
            for excluded in entry["excluded_metrics"]:
                lines.append(
                    f"- `{excluded['metric']}`: "
                    f"{_esc(excluded['reason'])}")
            lines.append("")
        lines.append(f"Notes: {_esc(entry['notes'])}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_baseline_book(
    entries: Any = None,
) -> Path:
    """Regenerate the filed book by command: render
    from the live registries and write the doc,
    byte for byte. Returns the doc's path."""
    doc = _REPO_ROOT / BASELINE_BOOK_DOC
    doc.write_text(
        render_baseline_book_markdown(entries),
        encoding="utf-8")
    return doc


def main(argv: Any = None) -> int:
    """The regeneration command's entry point:
    `python3 -m benchmarks.baseline_book`."""
    entries = book_entries()
    doc = write_baseline_book(entries)
    print(
        f"baseline book regenerated: {len(entries)} baselines / "
        f"{sum(len(e['metrics']) for e in entries)} pinned "
        f"metrics -> {BASELINE_BOOK_DOC}")
    return 0


# ── The pure drift checker (probes run here) ────────────────────────────────

def _split_sections(
    text: str,
) -> tuple[str, dict[str, str]]:
    """Split a book text into (header, sections by
    baseline id), purely: sections start at the
    '## Baseline `...`' headings the render files."""
    header_lines: list[str] = []
    sections: dict[str, str] = {}
    current: str | None = None
    buffer: list[str] = []
    for line in text.splitlines():
        if line.startswith("## Baseline `"):
            if current is None:
                header_lines = buffer
            else:
                sections[current] = "\n".join(buffer)
            current = line.split("`")[1]
            buffer = [line]
        else:
            buffer.append(line)
    if current is None:
        header_lines = buffer
    else:
        sections[current] = "\n".join(buffer)
    return "\n".join(header_lines), sections


def book_problems_for(
    filed_text: str, entries: Any = None,
) -> list[str]:
    """Judge a filed book text against the book
    regenerated from the live registries, purely:
    the header must match, every regenerated
    baseline's section must be present and exact,
    and no extra baseline section may stand. A
    stale value, a changed method, a moved
    tolerance, a flipped gate status — any drift
    inside a section — names that baseline."""
    rendered = render_baseline_book_markdown(entries)
    if filed_text == rendered:
        return []
    problems: list[str] = []
    filed_header, filed_sections = _split_sections(filed_text)
    live_header, live_sections = _split_sections(rendered)
    if filed_header != live_header:
        problems.append(
            "the filed book's header is stale vs the "
            "regenerated book (regenerate with "
            f"{REGENERATION_COMMAND})")
    for baseline_id, section in live_sections.items():
        if baseline_id not in filed_sections:
            problems.append(
                f"the filed book lost baseline "
                f"{baseline_id} (regenerate with "
                f"{REGENERATION_COMMAND})")
        elif filed_sections[baseline_id] != section:
            problems.append(
                f"the filed book's section for baseline "
                f"{baseline_id} is stale vs the live "
                f"registries (regenerate with "
                f"{REGENERATION_COMMAND})")
    for baseline_id in filed_sections:
        if baseline_id not in live_sections:
            problems.append(
                f"the filed book files baseline "
                f"{baseline_id}, which no registry "
                f"pins (the book is generated, never "
                f"hand-added to)")
    if not problems:
        problems.append(
            "the filed book is stale vs the regenerated "
            f"book (regenerate with {REGENERATION_COMMAND})")
    return problems


