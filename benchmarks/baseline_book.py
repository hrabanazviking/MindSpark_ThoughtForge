def _section_span(
    lines: list[str], baseline_id: str,
) -> tuple[int, int] | None:
    """The [start, end) line span of one baseline's
    section in a split book, or None."""
    start = None
    for index, line in enumerate(lines):
        if line.startswith("## Baseline `"):
            if start is not None:
                return start, index
            if line.split("`")[1] == baseline_id:
                start = index
    if start is None:
        return None
    return start, len(lines)


def _perturb_book(
    text: str, probe: dict[str, Any],
    entries: tuple[dict[str, Any], ...],
) -> str:
    """Apply one filed probe's perturbation to a
    copy of the regenerated book text, purely."""
    kind = probe["kind"]
    if kind == "clean":
        return text
    lines = text.splitlines()
    if kind == "extra_baseline":
        lines.extend([
            "", f"## Baseline `{probe['baseline']}`", "",
            "A hand-written section no registry pins."])
        return "\n".join(lines).rstrip() + "\n"
    span = _section_span(lines, probe["baseline"])
    if span is None:
        return text
    start, end = span
    entry = [e for e in entries
             if e["baseline"] == probe["baseline"]][0]
    if kind == "drop_baseline":
        del lines[start:end]
    elif kind == "metric_value":
        metric = [m for m in entry["metrics"]
                  if m["metric"] == probe["metric"]][0]
        old = f"| `{probe['metric']}` | " \
              f"{_value_text(metric['value'])} |"
        new = f"| `{probe['metric']}` | " \
              f"{_value_text(probe['new_value'])} |"
        for index in range(start, end):
            if old in lines[index]:
                lines[index] = lines[index].replace(old, new)
                break
    elif kind == "method_text":
        metric = [m for m in entry["metrics"]
                  if m["metric"] == probe["metric"]][0]
        old = _esc(metric["computes"])
        for index in range(start, end):
            if old in lines[index]:
                lines[index] = lines[index].replace(
                    old, probe["new_text"])
                break
    elif kind == "tolerance":
        old = f"- Tolerance: `{_value_text(entry['tolerance'])}`"
        new = f"- Tolerance: " \
              f"`{_value_text(probe['new_tolerance'])}`"
        for index in range(start, end):
            if lines[index] == old:
                lines[index] = new
                break
    elif kind == "gate_status":
        old = f"- Gate status: {entry['gate_status']}"
        flipped = (
            "ungated — judged by its own module's checker"
            if entry["gated"] else
            "gated by TF-129's regression gate")
        for index in range(start, end):
            if lines[index] == old:
                lines[index] = f"- Gate status: {flipped}"
                break
    return "\n".join(lines).rstrip() + "\n"


def run_book_probes() -> list[dict[str, Any]]:
    """Run the filed probes against the pure drift
    checker; each returns its verdict."""
    entries = book_entries()
    rendered = render_baseline_book_markdown(entries)
    results: list[dict[str, Any]] = []
    for probe in BOOK_PROBES:
        perturbed = _perturb_book(rendered, probe, entries)
        problems = book_problems_for(perturbed, entries)
        if probe["expect_problem"]:
            passed = bool(problems) and any(
                probe["baseline"] in p for p in problems)
        else:
            passed = problems == []
        results.append({
            "id": probe["id"], "passed": passed,
            "problems": problems,
            "detail": probe["detail"]})
    return results


# ── The book run ────────────────────────────────────────────────────────────

@dataclass
class BaselineBookResult:
    """One full book run: the entries it filed,
    the counts, and the verdict data."""

    entries: list[dict[str, Any]] = field(default_factory=list)
    doc_current: bool = False

    @property
    def total_baselines(self) -> int:
        return len(self.entries)

    @property
    def total_pinned_metrics(self) -> int:
        return sum(len(e["metrics"]) for e in self.entries)

    @property
    def gated_baselines(self) -> int:
        return sum(1 for e in self.entries if e["gated"])

    @property
    def ungated_baselines(self) -> int:
        return self.total_baselines - self.gated_baselines

    @property
    def overall_score(self) -> float:
        if not self.entries:
            return 0.0
        return 1.0 if self.doc_current else 0.0

    @property
    def verdict(self) -> str:
        """PASS only on the full book (every pinned
        baseline) with the filed doc reproducing
        the regenerated book exactly; REVIEW for
        any partial or empty selection, however it
        scores."""
        if [e["baseline"] for e in self.entries] != [
                b["id"] for b in _harness.BASELINES]:
            return "REVIEW"
        return "PASS" if self.doc_current else "REVIEW"

    @property
    def passes(self) -> bool:
        return self.verdict == "PASS"


def run_baseline_book(
    baseline_ids: Any = None,
) -> BaselineBookResult:
    """File the book over the selection (the full
    pinned estate by default): entries built live
    from the registries, and whether the filed doc
    is the regenerated book, byte for byte.

    Any explicit baseline selection may be given —
    including an empty one, which files 0 baselines
    / REVIEW (no vacuous pass).
    """
    entries = book_entries()
    if baseline_ids is not None:
        wanted = tuple(baseline_ids)
        entries = tuple(
            e for e in entries if e["baseline"] in wanted)
    doc = _REPO_ROOT / BASELINE_BOOK_DOC
    doc_current = bool(
        doc.exists()
        and doc.read_text(encoding="utf-8")
        == render_baseline_book_markdown())
    return BaselineBookResult(
        entries=[dict(e) for e in entries],
        doc_current=doc_current)


