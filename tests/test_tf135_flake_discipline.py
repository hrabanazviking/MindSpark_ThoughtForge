# The live census is the expensive leg (every
# pinned measurer x 5 repeats): the full run and
# the live checker each compute it once, and the
# tests below share those two computations
# within this file rather than re-running the
# census per test.
_CACHE: dict[str, object] = {}


def _full_result() -> FlakeDisciplineResult:
    if "full" not in _CACHE:
        _CACHE["full"] = run_flake_discipline()
    return _CACHE["full"]  # type: ignore[return-value]


def _checker() -> list[str]:
    if "checker" not in _CACHE:
        _CACHE["checker"] = flake_discipline_problems()
    return _CACHE["checker"]  # type: ignore[return-value]


def _row(baseline_id: str):
    return [r for r in CENSUS_ROWS
            if r["baseline"] == baseline_id][0]


