"""
TF-135 — Flake discipline: nondeterministic suites
quarantined or made deterministic (TF-036) — no
silent re-rolls.

The proof lives as verifiable data in
``benchmarks/flake_discipline.py`` (``CENSUS_ROWS``,
``QUARANTINE_REGISTRY``, ``FLAKE_REPORTS``,
``RERUN_RECORDS``, ``FLAKE_PROBES``, ``FLAKE_RULES``,
checked by ``flake_discipline_problems()``), the
rendered filing filed verbatim as
``docs/architecture/FLAKE_DISCIPLINE.md``,
registered in ``benchmarks/harness.py`` with the
pinned baseline ``flake_discipline_synthetic_v1``;
D-BENCH-20 (no flake discipline existed —
nondeterministic suites neither quarantined nor
made deterministic, the ungated baselines never
repeat-measured, and re-rolls silent) was fixed
by this slice.

Pinned here:

  * the census: 17 baselines re-measured 5 times
    in one process through the harness's own
    measurers (TF-129's NOISE_REPEATS widened to
    the whole estate) — 17 deterministic,
    0 quarantined, 6 metrics excluded-by-rule
    (TF-121's unpinned latency / wall / power
    shapes, never flakes),
  * the discipline: nondeterminism is FIXED
    (TF-036's determinism road) or QUARANTINED
    with a filed reason; no silent re-rolls —
    TF-126's EPERM re-roll is filed retroactively
    with its flake report and linked re-run
    record,
  * the pure validators: a census-perturbed
    suite, a reasonless quarantine, a report
    missing its differing values, a report
    missing its disposition and a silent re-roll
    record are each named — 7 filed probes, all
    behaving; empty filings are named, never
    crashed on,
  * the verdict shape: full census PASS, a full
    census carrying an unfiled nondeterminism
    FAIL, partial and empty selections REVIEW
    (no vacuous pass),
  * the checker clean, the harness registration
    (24 / 13 / 17 / 139, rules 17), the new
    baseline re-measured live twice — with every
    earlier pinned baseline preserved exactly
    (one deliberate exception, filed in the
    open: the baseline-book baseline was
    re-pinned for exactly this registry growth,
    15 -> 16 / 125 -> 132 / ungated 6 -> 7, and
    the book regenerated by its command; the
    hygiene inventory does NOT move, because the
    discipline adds no benchmark input) and
    TF-129's gated set untouched (the flake
    baseline is ungated, in the open),
  * TF-017 compliance: no canon access —
    risky markers assembled from parts.

All fixtures are synthetic (TF-017). Proof
grade: FIXTURE — no canon was opened, no live
model was read, never claimed (TF-173).
"""

