class TestCensus:
    def test_sixteen_baselines_all_deterministic_in_harness_order(
            self) -> None:
        assert len(CENSUS_ROWS) == 18
        assert [r["baseline"] for r in CENSUS_ROWS] == \
            [b["id"] for b in BASELINES]
        assert all(r["classification"] == "deterministic"
                   for r in CENSUS_ROWS)
        assert all(r["differing_metrics"] == []
                   for r in CENSUS_ROWS)
        assert all(r["max_abs_spread"] == 0.0
                   for r in CENSUS_ROWS)
        assert sum(r["metrics_measured"]
                   for r in CENSUS_ROWS) == 146
        # The quarantine registry files empty on
        # this tree: nothing differed, so nothing
        # is quarantined.
        assert QUARANTINE_REGISTRY == ()
        assert quarantine_reason_for(
            "persona_suite_synthetic_v1") is None

    def test_every_filed_row_validates_clean(self) -> None:
        for row in CENSUS_ROWS:
            assert census_row_problems(row) == []

    def test_repeats_match_tf129s_noise_repeats(self) -> None:
        assert CENSUS_REPEATS == NOISE_REPEATS == 5
        assert all(r["repeats"] == 5 for r in CENSUS_ROWS)

    def test_excluded_rows_are_tf121s_unpinned_shapes(
            self) -> None:
        excluded = excluded_metric_rows()
        assert len(excluded) == 6
        assert all(excluded_row_problems(r) == []
                   for r in excluded)
        by_baseline: dict[str, list[str]] = {}
        for row in excluded:
            by_baseline.setdefault(
                row["baseline"], []).append(row["metric"])
        assert by_baseline[
            "profile_benchmark_empty_store_v1"] == [
                "avg_latency_ms", "median_latency_ms",
                "p95_latency_ms"]
        assert by_baseline["cost_panel_synthetic_v1"] == [
            "cell_wall_time_ms", "power_watts"]
        assert by_baseline[
            FLAKE_DISCIPLINE_BASELINE_ID] == [
                "census_wall_time_s"]
        # Excluded-by-rule is a classification of
        # its own — never a flake, never a
        # determinism claim.
        assert all(r["classification"] == "excluded_by_rule"
                   for r in excluded)

    def test_tf036_determinism_is_cited(self) -> None:
        assert "TF-036" in DETERMINISM_CITATION
        assert "determinism" in DETERMINISM_CITATION
        entry = [b for b in BENCHMARKS
                 if b["id"] == "determinism"][0]
        assert "TF-135" in entry["suite_slice"]
        rule = [r for r in FLAKE_RULES if r["id"] ==
                "deterministic_means_every_repeat_"
                "reproduces_the_pin_exactly"][0]
        assert "TF-036" in rule["rule"]


