# ── The pure validator + probes ─────────────────────────────────────────────


class TestValidatorsAndProbes:
    def test_the_clean_shapes_pass_pure(self) -> None:
        assert claim_problems(
            copy.deepcopy(dict(CLAIM_ROWS[0]))) == []
        struck = [r for r in CLAIM_ROWS
                  if r["disposition"] == "struck"][0]
        assert claim_problems(copy.deepcopy(dict(struck))) == []

    def test_a_matched_claim_with_a_wrong_value_is_named(
            self) -> None:
        row = copy.deepcopy(dict(CLAIM_ROWS[0]))
        row["filed_value"] = 0.5
        problems = claim_problems(row)
        assert problems
        assert any(row["id"] in p for p in problems)
        assert any("wrong value" in p for p in problems)

    def test_a_struck_claim_that_actually_matches_is_named(
            self) -> None:
        struck = [r for r in CLAIM_ROWS
                  if r["disposition"] == "struck"][0]
        row = copy.deepcopy(dict(struck))
        row["baseline"] = "persona_suite_synthetic_v1"
        row["metric"] = "overall_score"
        row["filed_value"] = 0.8453703703703704
        problems = claim_problems(row)
        assert any("matched, not struck" in p for p in problems)

    def test_a_claim_missing_its_source_is_named(self) -> None:
        row = copy.deepcopy(dict(CLAIM_ROWS[0]))
        row["source"] = ""
        problems = claim_problems(row)
        assert any("no source" in p for p in problems)

    def test_a_matched_claim_missing_its_metric_is_named(
            self) -> None:
        row = copy.deepcopy(dict(CLAIM_ROWS[0]))
        row["metric"] = None
        problems = claim_problems(row)
        assert any("no metric" in p for p in problems)

    def test_empty_filings_are_named_never_crash(
            self) -> None:
        # The TF-130/132 class: a checker leg must
        # name an empty filing, not crash on it.
        assert claim_problems({})

    def test_seven_probes_all_behave(self) -> None:
        probes = run_claim_probes()
        assert len(probes) == len(CLAIM_PROBES) == 7
        assert all(p["passed"] for p in probes)
        by_id = {p["id"]: p for p in probes}
        assert by_id["clean_matched_claim_passes"][
            "problems"] == []
        assert by_id["clean_struck_claim_passes"][
            "problems"] == []
        assert by_id[
            "matched_claim_with_wrong_value_is_named"][
                "problems"]
        assert by_id[
            "struck_claim_that_actually_matches_is_named"][
                "problems"]
        assert by_id["claim_missing_source_is_named"][
            "problems"]
        assert by_id[
            "matched_claim_missing_metric_is_named"][
                "problems"]
        assert by_id[
            "empty_claim_is_named_never_crashed"]["problems"]


# ── The render (the doc, verbatim) ──────────────────────────────────────────


class TestRenderAndDoc:
    def test_the_filed_doc_is_the_render_verbatim(
            self) -> None:
        doc_text = (REPO_ROOT / PUBLIC_CLAIMS_DOC).read_text(
            encoding="utf-8")
        assert doc_text == render_public_claims_markdown()
        assert "Claims censused: 21" in doc_text
        assert "Matched claims: 12" in doc_text
        assert "Struck claims: 9" in doc_text
        assert "matched_means_a_live_verified_suite_value" \
            in doc_text
        for row in CLAIM_ROWS:
            assert f"`{row['id']}`" in doc_text

    def test_two_renders_are_byte_identical(self) -> None:
        assert render_public_claims_markdown() == \
            render_public_claims_markdown(CLAIM_ROWS)

    def test_the_cli_command_regenerates_the_doc(self) -> None:
        before = (REPO_ROOT / PUBLIC_CLAIMS_DOC).read_bytes()
        env = dict(os.environ)
        env["PYTHONPATH"] = os.pathsep.join(
            [str(REPO_ROOT / "src"), str(REPO_ROOT)])
        completed = subprocess.run(
            [sys.executable, "-m", "benchmarks.public_claims"],
            cwd=REPO_ROOT, env=env, capture_output=True,
            text=True, timeout=300)
        assert completed.returncode == 0
        assert "21 claims" in completed.stdout
        assert (REPO_ROOT / PUBLIC_CLAIMS_DOC).read_bytes() \
            == before


