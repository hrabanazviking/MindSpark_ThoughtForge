_CACHE: dict[str, object] = {}


def _checker() -> list[str]:
    if "checker" not in _CACHE:
        _CACHE["checker"] = public_claims_problems()
    return _CACHE["checker"]  # type: ignore[return-value]


def _row(claim_id: str):
    return [r for r in CLAIM_ROWS if r["id"] == claim_id][0]


# ── The census (filed rows) ─────────────────────────────────────────────────


class TestCensus:
    def test_twenty_one_claims_twelve_matched_nine_struck(
            self) -> None:
        assert len(CLAIM_ROWS) == 21
        matched = [r for r in CLAIM_ROWS
                   if r["disposition"] == "matched"]
        struck = [r for r in CLAIM_ROWS
                  if r["disposition"] == "struck"]
        assert len(matched) == 12
        assert len(struck) == 9
        assert len({r["source"] for r in CLAIM_ROWS}) == 12
        ids = [r["id"] for r in CLAIM_ROWS]
        assert len(ids) == len(set(ids))

    def test_every_filed_row_validates_clean(self) -> None:
        for row in CLAIM_ROWS:
            assert claim_problems(row) == [], row["id"]

    def test_every_source_exists_and_carries_its_marker(
            self) -> None:
        for row in CLAIM_ROWS:
            text = (REPO_ROOT / row["source"]).read_text(
                encoding="utf-8")
            assert row["marker"] in text, row["id"]

    def test_matched_rows_bind_real_pins(self) -> None:
        pins = {b["id"]: b["metrics"] for b in BASELINES}
        for row in CLAIM_ROWS:
            if row["disposition"] != "matched":
                continue
            assert pins[row["baseline"]][row["metric"]] == \
                row["filed_value"], row["id"]

    def test_the_struck_claims_are_named(self) -> None:
        struck = {r["id"] for r in CLAIM_ROWS
                  if r["disposition"] == "struck"}
        assert struck == {
            "model_card_citation_accuracy_target",
            "model_card_enforcement_pass_target",
            "model_card_avg_response_words_target",
            "model_card_persona_100_plus_turns",
            "build_plan_persona_100_plus_turns",
            "build_plan_citation_accuracy_85",
            "task_phase6_persona_100_plus_turns",
            "task_phase6_locust_httpuser",
            "model_card_edge_inference_speed"}
        for claim_id in struck:
            assert _row(claim_id)["reason"]

    def test_readme_is_never_a_filed_source(self) -> None:
        # The audit reads README.md for claims but
        # never edits it and files no strike against
        # it: no census row names it as a source.
        assert all(r["source"] != "README.md"
                   for r in CLAIM_ROWS)


