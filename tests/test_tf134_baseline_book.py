REPO_ROOT = Path(__file__).parent.parent


def _entry(baseline_id: str):
    return [e for e in BOOK_ENTRIES
            if e["baseline"] == baseline_id][0]


# ── The entries (built from the live registries) ────────────────────────────


class TestEntries:
    def test_sixteen_baselines_132_metrics_in_harness_order(
            self) -> None:
        assert len(BOOK_ENTRIES) == 16
        assert [e["baseline"] for e in BOOK_ENTRIES] == \
            [b["id"] for b in BASELINES]
        assert sum(len(e["metrics"]) for e in BOOK_ENTRIES) == 132
        assert book.TOTAL_BASELINES == 16
        assert book.TOTAL_PINNED_METRICS == 132

    def test_every_entry_files_its_method(self) -> None:
        for entry in BOOK_ENTRIES:
            assert entry_problems(entry) == []
            assert entry["measured_on"]
            assert entry["measurer"].startswith("measure_")
            assert entry["fixture"]
            assert entry["tolerance"] == 1e-9
            baseline = [b for b in BASELINES
                        if b["id"] == entry["baseline"]][0]
            assert entry["measured_on"] == baseline["measured_on"]
            assert entry["notes"] == baseline["notes"]

    def test_metric_values_and_methods_bind_the_registries(
            self) -> None:
        definitions = {(m["benchmark"], m["id"]): m
                       for m in METRIC_DEFINITIONS}
        for entry in BOOK_ENTRIES:
            baseline = [b for b in BASELINES
                        if b["id"] == entry["baseline"]][0]
            assert {m["metric"]: m["value"]
                    for m in entry["metrics"]} == \
                dict(baseline["metrics"])
            for metric in entry["metrics"]:
                assert metric["computes"] == definitions[
                    (entry["benchmark"], metric["metric"])
                ]["computes"]

    def test_gate_status_comes_from_tf129s_registries(self) -> None:
        gated = [e["baseline"] for e in BOOK_ENTRIES if e["gated"]]
        assert gated == list(GATED_BASELINE_IDS)
        assert len(gated) == 9
        assert sum(1 for e in BOOK_ENTRIES if not e["gated"]) == 7
        depth = _entry("depth_suite_synthetic_v1")
        assert depth["gate_status"].startswith("gated")
        for metric in depth["metrics"]:
            assert metric["gate_tolerance"] is not None
        own = _entry(BASELINE_BOOK_BASELINE_ID)
        assert own["gated"] is False
        assert all(m["gate_tolerance"] is None
                   for m in own["metrics"])


# ── Regeneration by command ─────────────────────────────────────────────────


class TestRegeneration:
    def test_the_filed_doc_is_the_render_byte_for_byte(self) -> None:
        doc_text = (REPO_ROOT / BASELINE_BOOK_DOC).read_text(
            encoding="utf-8")
        assert doc_text == render_baseline_book_markdown()
        assert doc_text == render_baseline_book_markdown(
            book_entries())

    def test_two_renders_are_byte_identical(self) -> None:
        assert render_baseline_book_markdown() == \
            render_baseline_book_markdown(book_entries())

    def test_write_baseline_book_reproduces_the_doc(self,
            tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        before = (REPO_ROOT / BASELINE_BOOK_DOC).read_bytes()
        written = write_baseline_book()
        assert written == REPO_ROOT / BASELINE_BOOK_DOC
        assert (REPO_ROOT / BASELINE_BOOK_DOC).read_bytes() == before

    def test_the_cli_command_regenerates_the_book(self) -> None:
        before = (REPO_ROOT / BASELINE_BOOK_DOC).read_bytes()
        env = dict(os.environ)
        env["PYTHONPATH"] = os.pathsep.join(
            [str(REPO_ROOT / "src"), str(REPO_ROOT)])
        completed = subprocess.run(
            [sys.executable, "-m", "benchmarks.baseline_book"],
            cwd=REPO_ROOT, env=env, capture_output=True,
            text=True, timeout=300)
        assert completed.returncode == 0
        assert "16 baselines / 132 pinned metrics" in \
            completed.stdout
        assert (REPO_ROOT / BASELINE_BOOK_DOC).read_bytes() == before
        assert REGENERATION_COMMAND == \
            "python3 -m benchmarks.baseline_book"

    def test_the_book_names_every_baseline_and_method(self) -> None:
        text = render_baseline_book_markdown()
        for entry in BOOK_ENTRIES:
            assert f"## Baseline `{entry['baseline']}`" in text
            assert entry["measurer"] in text
            for metric in entry["metrics"]:
                assert f"`{metric['metric']}`" in text


# ── Drift detection + probes ────────────────────────────────────────────────


class TestDriftAndProbes:
    def test_the_clean_book_files_no_problem(self) -> None:
        assert book_problems_for(
            render_baseline_book_markdown()) == []

    def test_a_stale_metric_value_is_named(self) -> None:
        text = render_baseline_book_markdown()
        stale = text.replace(
            "0.7166666666666667", "0.5", 1)
        problems = book_problems_for(stale)
        assert problems
        assert any("persona_consistency_synthetic_v1" in p
                   for p in problems)

    def test_a_dropped_baseline_is_named(self) -> None:
        text = render_baseline_book_markdown()
        head, _, _ = text.partition(
            "## Baseline `presence_suite_synthetic_v1`")
        problems = book_problems_for(head)
        assert any("presence_suite_synthetic_v1" in p
                   for p in problems)

    def test_a_hand_added_baseline_is_named(self) -> None:
        text = render_baseline_book_markdown() + (
            "\n## Baseline `hand_written_v1`\n\ninvented.\n")
        problems = book_problems_for(text)
        assert any("hand_written_v1" in p for p in problems)

    def test_seven_probes_all_behave(self) -> None:
        probes = run_book_probes()
        assert len(probes) == len(BOOK_PROBES) == 7
        assert all(p["passed"] for p in probes)
        by_id = {p["id"]: p for p in probes}
        assert by_id["clean_regenerated_book_passes"]["problems"] == []
        assert by_id["stale_metric_value_is_named"]["problems"]
        assert by_id["wrong_method_line_is_named"]["problems"]
        assert by_id["wrong_tolerance_is_named"]["problems"]
        assert by_id["flipped_gate_status_is_named"]["problems"]
        assert by_id["dropped_baseline_is_named"]["problems"]
        assert by_id["hand_added_baseline_is_named"]["problems"]


